def split_briefs(seed: int = 0) -> dict[str, list[Brief]]:
    """Fixed half/half split; pro and contra of one topic may land in different splits, which is fine."""
    order = list(BRIEFS)
    random.Random(seed).shuffle(order)
    half = len(order) // 2
    return {"explore": order[:half], "confirm": order[half:]}


def as_dict(b: Brief) -> dict:
    return asdict(b)
